/*
A small warehouse tracks how many units of different products are shipped from multiple branches. Another dataset shows how much revenue each product generates per unit. Develop a C program which combines these datasets to calculate the total revenue generated by each branch.
*/

#include <stdio.h>

int main()
{
    int branches, products;
    int i, j;

    printf("Enter number of branches: ");
    scanf("%d", &branches);

    printf("Enter number of products: ");
    scanf("%d", &products);

    int units[branches][products];
    float price[products];
    float totalRevenue;

    // Input units shipped
    printf("\nEnter units shipped by each branch:\n");
    for (i = 0; i < branches; i++)
    {
        printf("Branch %d:\n", i + 1);
        for (j = 0; j < products; j++)
        {
            printf("  Product %d units: ", j + 1);
            scanf("%d", &units[i][j]);
        }
    }

    // Input revenue per unit
    printf("\nEnter revenue per unit for each product:\n");
    for (j = 0; j < products; j++)
    {
        printf("Product %d price: ", j + 1);
        scanf("%f", &price[j]);
    }

    // Calculate revenue for each branch
    printf("\nTotal Revenue Generated by Each Branch:\n");

    for (i = 0; i < branches; i++)
    {
        totalRevenue = 0;

        for (j = 0; j < products; j++)
        {
            totalRevenue += units[i][j] * price[j];
        }

        printf("Branch %d Revenue = %.2f\n",
               i + 1, totalRevenue);
    }

    return 0;
}

